def test_发布中途缺正式行_整票回滚_封印不动(tmp_path):
    _准备三日()
    封印.封印当日(日)
    原指纹 = _正式指纹()
    _开窗("票-半截-1")
    封印.迟到补抽(日, _迟到流水("流-半截-1", 700), "批-半截", "票-半截-1")
    # 制造半截：物理抹掉户甲正式行（绕过服务层），发布须检测并全量回滚
    conn = 连接()
    try:
        conn.execute("DELETE FROM 周期快照 WHERE 账户键='户甲' AND 营业日=?", (日,))
        conn.commit()
    finally:
        conn.close()
    with pytest.raises(ValueError):
        窗票.发布("票-半截-1", 原因="半截试探")
    conn = 连接()
    try:
        票 = conn.execute("SELECT 状态 FROM 解封窗票表 WHERE 票号='票-半截-1'").fetchone()
        assert 票["状态"] == "在窗", "失败闭：票状态不得半改"
        簿行 = conn.execute("SELECT 状态 FROM 纠偏簿 WHERE 票号='票-半截-1'").fetchone()
        assert 簿行["状态"] == "待发布"
        封 = conn.execute("SELECT 正式指纹 FROM 封印 WHERE 营业日=?", (日,)).fetchone()
        assert 封["正式指纹"] == 原指纹
    finally:
        conn.close()

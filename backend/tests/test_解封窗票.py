# ---------- 抢锁并发 ----------

def test_开窗与补抽抢锁_不得无票正式已改():
    """并发夹具：补抽线程与开窗线程同时冲入。

    口径乙下正式镜结构上永冻；无论交错如何：正式指纹恒等封印指纹、
    纠偏簿只可能由持有效票的补抽写入、无票补抽必须失败闭。
    """
    _准备三日()
    封印.封印当日(日)
    原指纹 = _正式指纹()
    原余额 = _户甲正式余额()
    错误: list = []
    闸 = threading.Barrier(8)

    def 开() -> None:
        try:
            闸.wait()
            窗票.开窗(日, 窗止="2099-01-01T00:00:00Z", 票号=f"票-并发-{threading.get_ident()}",
                      原因="并发开窗")
        except Exception as e:
            错误.append(e)

    def 补(持票: bool) -> None:
        try:
            闸.wait()
            号 = f"票-并发-{threading.get_ident()}" if 持票 else ""
            封印.迟到补抽(日, _迟到流水(f"流-并发-{threading.get_ident()}", 100),
                          f"批-并发-{threading.get_ident()}", 号)
        except ValueError:
            pass  # 无票/票尚未落成被拒是预期
        except Exception as e:
            错误.append(e)

    threads = [threading.Thread(target=开) for _ in range(4)]
    threads += [threading.Thread(target=补, args=(False,)) for _ in range(2)]
    threads += [threading.Thread(target=补, args=(True,)) for _ in range(2)]
    for t in threads:
        t.start()
    for t in threads:
        t.join()

    assert not 错误, f"并发不应出现非闸口异常: {错误}"
    assert _正式指纹() == 原指纹, "抢锁下正式指纹不得变"
    assert _户甲正式余额() == 原余额
    核 = 封印.核证(日)
    assert 核["valid"] is True
    # 纠偏簿若有行，必挂在真实存在且同营业日的票上
    for r in 窗票.列纠偏(日):
        票 = 窗票.核证(r["票号"])
        assert 票["营业日"] == 日 and 票["正式指纹"] == 原指纹



"""解封窗票 · 口径乙 夹具（全局唯一口径：窗票只开待发布纠偏簿，正式指纹永冻）。

覆盖：
1. 封印→开窗→持票迟到补抽：正式有效余额不变、纠偏簿可读；回放差额仍按正式镜漂。
2. 无窗票补抽：正式与纠偏簿两端皆拒（失败闭，流水不污染）。
3. 窗票过期后再补抽：拒改正式、拒写纠偏簿（拨钟夹具）。
4. 开窗与补抽抢锁：不得出现无票正式已改；窗内补抽只落纠偏簿。
5. 发布解封：同写锁内并正式，封印指纹重算；无原因/无纠偏/已发布皆拒。
6. 普通解封联动在窗票作废、待发布纠偏作废。
7. 范围票超账户拒写纠偏簿；窗起止/营业日/票号同票核证。
8. 核证只读接口契约：票号、窗是否有效、正式指纹、纠偏簿有无、valid。
9. 半截失败闭：发布中途缺正式行 → 全量回滚，封印标记与正式指纹不动。
"""

import json
import threading
from pathlib import Path

import pytest

from app.db import 连接
from app.services import 回放, 抽取, 封印, 时间
from app.modules import 解封窗票 as 窗票

夹具 = Path(__file__).resolve().parents[2] / "fixtures"
日 = "2026-11-22"


def _装夹具(名: str, 批: str = "") -> dict:
    data = json.loads((夹具 / 名).read_text(encoding="utf-8"))
    from app.services.装载 import 装载流水

    return 装载流水(data["流水"], 批 or data.get("批次编号") or 名.replace(".json", ""))


def _准备三日() -> None:
    _装夹具("三日连环样例.json")
    for d in ("2026-11-20", "2026-11-21", 日):
        抽取.日终抽取(d)
    回放.回放核对(日)


def _正式指纹(d: str = 日) -> str:
    return 封印.核证(d)["正式指纹"]


def _户甲正式余额() -> int:
    conn = 连接()
    try:
        return int(conn.execute(
            "SELECT 余额 FROM 周期快照 WHERE 账户键='户甲' AND 营业日=? AND 状态='有效'",
            (日,),
        ).fetchone()["余额"])
    finally:
        conn.close()


def _迟到流水(号: str, 额: int) -> list[dict]:
    return [
        {
            "流水号": 号,
            "账户键": "户甲",
            "营业日": 日,
            "发生时": f"{日}T23:30:00Z",
            "变动额": 额,
            "摘要": "迟到补入",
        }
    ]


def _开窗(票号: str, 窗止: str = "2099-01-01T00:00:00Z", **kw) -> dict:
    return 窗票.开窗(日, 窗止=窗止, 票号=票号, 原因="测试开窗", **kw)


# ---------- 口径乙可区分性核心断言 ----------

def test_持票迟到补抽_正式不变_纠偏簿可读_与直改口徑可区分():
    _准备三日()
    封印.封印当日(日, 原因="定版")
    原指纹 = _正式指纹()
    原余额 = _户甲正式余额()

    _开窗("票-核心-1")
    果 = 封印.迟到补抽(日, _迟到流水("流-核心-1", 700), "批-核心-1", "票-核心-1")

    # 口径乙的可区分点：正式有效余额不变；待发布纠偏簿可读
    assert _户甲正式余额() == 原余额, "正式有效镜永冻"
    assert _正式指纹() == 原指纹
    簿 = 窗票.列纠偏(日, "票-核心-1")
    assert len(簿) == 3, "日终抽取按全账户写纠偏（三户）"
    行 = next(r for r in 簿 if r["账户键"] == "户甲")
    assert 行["正式余额"] == 原余额
    assert 行["纠偏余额"] == 原余额 + 700
    assert 行["差额"] == 700 and 行["状态"] == "待发布"
    assert 果["抽取"]["纠偏写入"] == 3
    assert 果["抽取"]["盖写"] == 0 and 果["抽取"]["写入"] == 0
    # 主读快照不含纠偏值；核证 valid
    assert 封印.核证(日)["valid"] is True
    核 = 窗票.核证("票-核心-1")
    assert 核["窗是否有效"] is True and 核["valid"] is True
    assert 核["纠偏簿有无"] is True and 核["待发布行数"] == 3
    assert 核["正式指纹"] == 原指纹
    # 同票留痕：开窗、写纠偏簿审计可按票号查
    动作 = {a["动作"]: a["结果"] for a in 窗票.列审计("票-核心-1")}
    assert 动作.get("开窗") == "通过"
    assert 动作.get("写纠偏簿") == "通过"


